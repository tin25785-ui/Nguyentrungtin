# 1. Khai báo các biến với kiểu dữ liệu khác nhau
ho_ten = "Nguyễn Trung Tín"       # Kiểu str (chuỗi)
tuoi = 20                        # Kiểu int (số nguyên)
chieu_cao = 1.75                 # Kiểu float (số thực)
la_sinh_vien = True              # Kiểu bool (đúng/sai)

# 2. In ra màn hình bằng f-string
print(f"Họ tên: {ho_ten}")
print(f"Tuổi: {tuoi}")
print(f"Chiều cao: {chieu_cao}m")
print(f"Đang là sinh viên: {la_sinh_vien}")